"""Build the word lists the chat checks use, from the prepared MedQuAD data.

- pha/chat/long_words.txt: long words from MedQuAD answers, for the gibberish guard. Mashed
  output such as "healthatheliefallithere" is made of long tokens that appear in no medical
  text; real long words ("hyperparathyroidism") do.
- pha/chat/words.txt: every word seen at least twice in questions and answers, with its count,
  for asking the user to clarify messages made only of unknown words (pha/chat/clarify.py).

Run after training/prepare_medquad.py:

    uv run python scripts/build_guard_vocab.py ../data/medquad-v3
"""

import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pha.chat.clarify import WORD as MESSAGE_WORD  # noqa: E402
from pha.chat.guard import LONG_WORD_MIN, WORD, stem  # noqa: E402

CHAT = Path(__file__).resolve().parents[1] / "pha" / "chat"
OUT = CHAT / "long_words.txt"
WORDS_OUT = CHAT / "words.txt"
MIN_COUNT = 2  # a word seen once may be a typo in the source
WORDS_HEADER = (
    "# Words seen at least twice in MedQuAD questions and answers (Ben Abacha & Demner-Fushman,\n"
    "# BMC Bioinformatics 2019; CC BY 4.0) and the synthetic training records, with counts.\n"
    "# Generated by backend/scripts/build_guard_vocab.py.\n"
)
HEADER = (
    "# Long words seen in MedQuAD answers (Ben Abacha & Demner-Fushman, BMC Bioinformatics 2019;\n"
    "# CC BY 4.0), stemmed. Generated by backend/scripts/build_guard_vocab.py.\n"
)


def main(data_dir: str) -> None:
    words: set[str] = set()
    counts: Counter[str] = Counter()
    for split in ("train", "val", "test"):
        for line in (Path(data_dir) / f"{split}.jsonl").read_text().splitlines():
            for message in json.loads(line)["messages"]:
                if message["role"] in ("user", "assistant"):
                    counts.update(MESSAGE_WORD.findall(message["content"].lower()))
                if message["role"] == "assistant":
                    words |= {
                        stem(w)
                        for w in WORD.findall(message["content"])
                        if len(w) >= LONG_WORD_MIN - 2
                    }
    OUT.write_text(HEADER + "\n".join(sorted(words)) + "\n")
    print(f"wrote {len(words)} words to {OUT}")
    common = sorted(w for w, n in counts.items() if n >= MIN_COUNT and w.isascii())
    WORDS_OUT.write_text(WORDS_HEADER + "".join(f"{w} {counts[w]}\n" for w in common))
    print(f"wrote {len(common)} words to {WORDS_OUT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../data/medquad-v3")
